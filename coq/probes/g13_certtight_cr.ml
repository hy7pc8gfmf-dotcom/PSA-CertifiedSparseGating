module Z =
 struct
  (** val mul : z -> z -> z **)

  let mul x y =
    match x with
    | Z0 -> Z0
    | Zpos x' ->
      (match y with
       | Z0 -> Z0
       | Zpos y' -> Zpos (Pos.mul x' y')
       | Zneg y' -> Zneg (Pos.mul x' y'))
    | Zneg x' ->
      (match y with
       | Z0 -> Z0
       | Zpos y' -> Zneg (Pos.mul x' y')
       | Zneg y' -> Zpos (Pos.mul x' y'))

  (** val compare : z -> z -> comparison **)

  let compare x y =
    match x with
    | Z0 -> (match y with
             | Z0 -> Eq
             | Zpos _ -> Lt
             | Zneg _ -> Gt)
    | Zpos x' -> (match y with
                  | Zpos y' -> Pos.compare x' y'
                  | _ -> Gt)
    | Zneg x' ->
      (match y with
       | Zneg y' -> compOpp (Pos.compare x' y')
       | _ -> Lt)

  (** val leb : z -> z -> bool **)

  let leb x y =
    match compare x y with
    | Gt -> False
    | _ -> True
 end

type q = { qnum : z; qden : positive }

(** val qle_bool : q -> q -> bool **)

let qle_bool x y =
  Z.leb (Z.mul x.qnum (Zpos y.qden)) (Z.mul y.qnum (Zpos x.qden))

(** val qmult : q -> q -> q **)

let qmult x y =
  { qnum = (Z.mul x.qnum y.qnum); qden = (Coq_Pos.mul x.qden y.qden) }

type ct_cert = { ct_m : q; ct_sb : q; ct_sq : q }

(** val ct_pos : ct_cert -> bool **)

let ct_pos c =
  match match qle_bool { qnum = Z0; qden = XH } c.ct_m with
        | True -> qle_bool { qnum = (Zpos XH); qden = XH } c.ct_sb
        | False -> False with
  | True -> qle_bool { qnum = (Zpos XH); qden = XH } c.ct_sq
  | False -> False

(** val ct_ref : ct_cert -> ct_cert -> bool **)

let ct_ref a b =
  match match qle_bool b.ct_m a.ct_m with
        | True -> qle_bool a.ct_sb b.ct_sb
        | False -> False with
  | True -> qle_bool a.ct_sq b.ct_sq
  | False -> False

(** val ct_check : ct_cert -> bool **)

let ct_check c =
  qle_bool (qmult { qnum = (Zpos (XI (XO XH))); qden = XH } c.ct_m)
    (qmult { qnum = (Zpos (XO (XO XH))); qden = XH } (qmult c.ct_sb c.ct_sq))

(** val ct_tighten : ct_cert -> ct_cert list -> ct_cert **)

let rec ct_tighten cur = function
| Nil -> cur
| Cons (c, t) ->
  (match match ct_ref cur c with
         | True -> ct_pos c
         | False -> False with
   | True -> ct_tighten c t
   | False -> ct_tighten cur t)

(** val ct_opt_cert : ct_cert -> ct_cert list -> (ct_cert, __) sigT **)

let ct_opt_cert c0 l =
  ExistT ((ct_tighten c0 l), __)
